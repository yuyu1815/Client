/// Exact registered-state lookup for serialized block-state properties.
pub(crate) fn state_with_properties(
    name: &str,
    properties: &[(String, String)],
) -> Option<BlockState> {
    all_states()
        .find(|(_, data)| {
            data.id == name
                && data.properties.entries().count() == properties.len()
                && data
                    .properties
                    .entries()
                    .all(|(key, value)| properties.iter().any(|(k, v)| k == key && v == value))
        })
        .map(|(state, _)| state)
}

/// Exact registered state lookup for NBT forms that omit `Properties`.
pub(crate) fn state_without_properties(name: &str) -> Option<BlockState> {
    state_with_properties(name, &[])
}

pub(crate) fn water_source_state() -> BlockState {
    all_states()
        .find(|(_, d)| d.id == "water" && d.properties.get("level") == Some("0"))
        .map(|(state, _)| state)
        .expect("vanilla water source state must exist")
}

/// Converts a wire-side numeric state id, validated against the loaded table.
pub fn try_state(id: u32) -> Option<BlockState> {
    if (id as usize) < table().len() {
        BlockState::try_from(id).ok()
    } else {
        None
    }
}

/// Vanilla LevelChunk's debug-world read override, including in Nether/End.
/// Built once per level from the active protocol table (the vanilla registry
/// order).
#[derive(Clone, Copy)]
pub(crate) struct DebugWorld {
    width: i32,
    height: i32,
    barrier: BlockState,
}

impl DebugWorld {
    pub fn new() -> Self {
        let count = table().len();
        let width = (count as f32).sqrt().ceil() as i32;
        Self {
            width,
            height: count.div_ceil(width as usize) as i32,
            // Barrier's first enumerated state is waterlogged; vanilla uses its dry default.
            barrier: all_states()
                .find(|(_, d)| d.id == "barrier" && d.properties.get("waterlogged") != Some("true"))
                .expect("vanilla debug world requires barrier")
                .0,
        }
    }

    pub fn state(self, x: i32, y: i32, z: i32) -> BlockState {
        if y == 60 {
            return self.barrier;
        }
        if y == 70 && x > 0 && z > 0 && x % 2 != 0 && z % 2 != 0 {
            let (x, z) = (x / 2, z / 2);
            // DebugLevelSource.getBlockStateFor uses inclusive grid bounds.
            if x <= self.width && z <= self.height {
                return try_state((x * self.width + z) as u32).unwrap_or(BlockState::AIR);
            }
        }
        BlockState::AIR
    }
}

