/// Vanilla getFluidState overrides on blocks without a `waterlogged` property.
const IMPLICIT_WATER: [&str; 4] = ["seagrass", "tall_seagrass", "kelp", "kelp_plant"];

/// Loads the block-state table for the launched game version. Must be called
/// once at startup before any world/render code runs.
pub fn init(version: &str) {
    let protocol = pomme_protocol::ProtocolVersion::from_name(version)
        .map(|v| v.protocol)
        .unwrap_or_else(|| {
            tracing::warn!(
                "no block-state data for version {version}, using {} — expect state drift",
                pomme_protocol::version::NATIVE.name
            );
            pomme_protocol::version::NATIVE.protocol
        });
    set_active_protocol(protocol);
}

/// Switches the active table to the given protocol's, building it on first
/// use, so state ids from the wire are interpreted natively in that
/// version's id space (no chunk remapping). Patch releases sharing a
/// protocol number (26.1 through 26.1.2 are all 775) get the same table.
/// Only safe between worlds — meshes built against the previous table
/// interpret ids in the old id space.
pub fn set_active_protocol(protocol: i32) {
    let slot = prewarm_protocol(protocol);
    ACTIVE_TABLE.store(slot, std::sync::atomic::Ordering::Release);
}

/// Builds the given protocol's table if it isn't already, without switching
/// to it; safe at any time (e.g. from a server-list ping, ahead of the join).
pub fn prewarm_protocol(protocol: i32) -> usize {
    let slot = block_data_slot(protocol).unwrap_or(NATIVE_SLOT);
    BLOCK_TABLES[slot].get_or_init(|| build_table(&BLOCK_DATA[slot]));
    slot
}

/// Resolve a protocol's block registry entry index to its identity using the
/// same versioned generated block table used for that protocol's states.
pub fn block_name_for_registry_id(protocol: i32, id: u32) -> Option<String> {
    let slot = block_data_slot(protocol)?;
    let file: BlockFile = serde_json::from_str(BLOCK_DATA[slot].blocks).ok()?;
    file.blocks.get(id as usize).map(|entry| entry.name.clone())
}

/// The `BLOCK_DATA` slot serving a protocol, through `SHARED_BLOCK_DATA`.
fn block_data_slot(protocol: i32) -> Option<usize> {
    let protocol = SHARED_BLOCK_DATA
        .iter()
        .find(|&&(p, _)| p == protocol)
        .map_or(protocol, |&(_, shared)| shared);
    BLOCK_DATA.iter().position(|d| d.protocol == protocol)
}

fn load_behaviors() -> HashMap<String, BehaviorEntry> {
    serde_json::from_str(include_str!("data/block_behavior.json"))
        .expect("invalid block-behavior data")
}

fn validate_shape_boxes(shapes: &[Vec<LocalBox>]) {
    for (shape_index, shape) in shapes.iter().enumerate() {
        for (box_index, bounds) in shape.iter().enumerate() {
            assert!(
                bounds.iter().all(|coordinate| coordinate.is_finite()),
                "shape {shape_index} box {box_index} has a non-finite coordinate"
            );
            for axis in 0..3 {
                assert!(
                    bounds[axis] <= bounds[axis + 3],
                    "shape {shape_index} box {box_index} has inverted bounds on axis {axis}"
                );
            }
        }
    }
}

fn build_table(data: &EmbeddedBlocks) -> Vec<BlockData> {
    let file: BlockFile = serde_json::from_str(data.blocks).expect("invalid block-state data");
    assert_eq!(
        pomme_protocol::ProtocolVersion::from_name(&file.version).map(|v| v.protocol),
        Some(data.protocol),
        "block data for {} is keyed to protocol {}",
        file.version,
        data.protocol
    );
    let behaviors = load_behaviors();
    let state_file: StateFile = serde_json::from_str(data.state).expect("invalid state data");
    assert_eq!(
        state_file.version, file.version,
        "state data is for a different version"
    );
    assert_eq!(
        state_file.state_count, file.state_count,
        "state data state count mismatch"
    );
    assert_eq!(
        state_file.blocks.len(),
        file.blocks.len(),
        "state data block count mismatch"
    );
    let shape_file = data.shapes.map(|json| {
        let shapes: ShapeFile = serde_json::from_str(json).expect("invalid block-shape data");
        validate_shape_boxes(&shapes.shapes);
        assert_eq!(
            shapes.version, file.version,
            "shape data is for a different version"
        );
        assert_eq!(
            shapes.state_count, file.state_count,
            "shape data state count mismatch"
        );
        assert_eq!(
            shapes.verified_states + shapes.skipped_states,
            shapes.state_count,
            "shape data coverage mismatch"
        );
        assert_eq!(
            shapes.context_dependent_states
                + shapes.offset_dependent_states
                + shapes.oracle_disagreement_states,
            shapes.skipped_states,
            "shape data skip counts mismatch"
        );
        assert_eq!(
            shapes.blocks.len(),
            file.blocks.len(),
            "shape data block count mismatch"
        );
        shapes
    });
    let masks: &'static [FaceMask] = Vec::leak(
        state_file
            .masks
            .iter()
            .map(|hex| decode_face_mask(hex))
            .collect(),
    );
    // The same handful of 6-mask tuples repeats across thousands of states;
    // dedupe them into leaked statics so each state stores one pointer.
    let mut tuples: HashMap<[u32; 6], &'static [FaceMask; 6]> = HashMap::new();
    let mut tuple = |indices: [u32; 6]| -> &'static [FaceMask; 6] {
        tuples
            .entry(indices)
            .or_insert_with(|| Box::leak(Box::new(indices.map(|i| masks[i as usize]))))
    };

    let mut interner: HashSet<&'static str> = HashSet::new();
    let mut intern = |s: &str| -> &'static str {
        match interner.get(s) {
            Some(&e) => e,
            None => {
                let leaked: &'static str = Box::leak(s.to_string().into_boxed_str());
                interner.insert(leaked);
                leaked
            }
        }
    };

    let mut table: Vec<BlockData> = Vec::with_capacity(file.state_count as usize);
    for (block_index, (block, state_entry)) in
        file.blocks.iter().zip(&state_file.blocks).enumerate()
    {
        assert_eq!(
            block.first_id,
            table.len() as u32,
            "block-state data not dense at '{}'",
            block.name
        );
        let shape_block = shape_file.as_ref().map(|file| {
            let entry = &file.blocks[block_index];
            assert_eq!(entry.name, block.name, "shape block order mismatch");
            assert_eq!(
                entry.first_id, block.first_id,
                "shape block state id mismatch"
            );
            assert_eq!(entry.props, block.props, "shape block properties mismatch");
            entry
        });
        assert_eq!(
            state_entry.name, block.name,
            "state data out of order at '{}'",
            block.name
        );
        let name = intern(&block.name);
        let behavior = match behaviors.get(&block.name) {
            Some(b) => BlockBehavior {
                destroy_time: b.destroy_time,
                requires_correct_tool_for_drops: b.requires_correct_tool,
            },
            None => {
                tracing::warn!("no behavior entry for block '{}', using defaults", name);
                DEFAULT_BEHAVIOR
            }
        };
        let props: Vec<(&'static str, Vec<&'static str>)> = block
            .props
            .iter()
            .map(|(k, vs)| (intern(k), vs.iter().map(|v| intern(v)).collect()))
            .collect();
        let is_air = matches!(block.name.as_str(), "air" | "cave_air" | "void_air");
        let collides = state_entry.c != 0;

        let count: u32 = props.iter().map(|(_, vs)| vs.len() as u32).product();
        assert!((block.first_id..block.first_id + count).contains(&block.default_id));
        if let Some(entry) = shape_block {
            let mut previous = None;
            for shape in &entry.overrides {
                assert!(
                    shape.0 < count,
                    "shape offset out of range for {}",
                    block.name
                );
                assert!(
                    previous.map_or(true, |offset| shape.0 > offset),
                    "shape offsets not strictly ordered for {}",
                    block.name
                );
                previous = Some(shape.0);
            }
        }
        let default_state =
            BlockState::try_from(block.default_id).expect("default state fits id repr");
        let face_indices = light_face_indices(state_entry, count as usize);
        for offset in 0..count {
            let mut pairs = Vec::with_capacity(props.len());
            let mut stride = count;
            for (key, values) in &props {
                stride /= values.len() as u32;
                pairs.push((*key, values[(offset / stride) as usize % values.len()]));
            }
            let properties = PropMap::from_pairs(pairs);
            let fluid = state_fluid(name, &properties);
            let override_shape = shape_block.and_then(|block| {
                block
                    .overrides
                    .binary_search_by_key(&offset, |shape| shape.0)
                    .ok()
                    .map(|index| &block.overrides[index])
            });
            let (shape, outline) = if let Some(exact) = override_shape {
                let collision = shape_file
                    .as_ref()
                    .expect("shape override requires its shape file")
                    .shapes
                    .get(exact.1 as usize)
                    .unwrap_or_else(|| {
                        panic!("collision shape index out of range for {}", block.name)
                    })
                    .clone();
                let outline = shape_file
                    .as_ref()
                    .expect("shape override requires its shape file")
                    .shapes
                    .get(exact.2 as usize)
                    .unwrap_or_else(|| {
                        panic!("outline shape index out of range for {}", block.name)
                    })
                    .clone();
                let full_cube = [[0.0, 0.0, 0.0, 1.0, 1.0, 1.0]];
                let collision_field = (collision.as_slice() != full_cube.as_slice())
                    .then(|| collision.clone().into_boxed_slice());
                let outline_field = (outline != collision).then(|| outline.into_boxed_slice());
                (collision_field, outline_field)
            } else if file.version != "26.2"
                && matches!(
                    name,
                    "mangrove_propagule"
                        | "dandelion"
                        | "golden_dandelion"
                        | "torchflower"
                        | "poppy"
                        | "blue_orchid"
                        | "allium"
                        | "azure_bluet"
                        | "red_tulip"
                        | "orange_tulip"
                        | "white_tulip"
                        | "pink_tulip"
                        | "oxeye_daisy"
                        | "cornflower"
                        | "wither_rose"
                        | "lily_of_the_valley"
                        | "bamboo_sapling"
                        | "bamboo"
                        | "pointed_dripstone"
                        | "sulfur_spike"
                        | "open_eyeblossom"
                        | "closed_eyeblossom"
                )
            {
                (None, None)
            } else {
                (
                    compute_shape(name, &properties).map(Vec::into_boxed_slice),
                    compute_outline(name, &properties).map(Vec::into_boxed_slice),
                )
            };
            let max_horizontal_offset = if file.version == "26.2" {
                match name {
                    "mangrove_propagule" | "dandelion" | "golden_dandelion" | "torchflower"
                    | "poppy" | "blue_orchid" | "allium" | "azure_bluet" | "red_tulip"
                    | "orange_tulip" | "white_tulip" | "pink_tulip" | "oxeye_daisy"
                    | "cornflower" | "wither_rose" | "lily_of_the_valley" | "bamboo_sapling"
                    | "bamboo" | "open_eyeblossom" | "closed_eyeblossom" => 0.25,
                    "pointed_dripstone" | "sulfur_spike" => 0.125,
                    _ => 0.0,
                }
            } else {
                0.0
            };
            let light = LightProps {
                emission: state_entry.e.get(offset as usize),
                dampening: state_entry.d.get(offset as usize),
                propagates_skylight_down: state_entry.p.get(offset as usize) != 0,
                can_occlude: state_entry.o.get(offset as usize) != 0,
                use_shape_for_light_occlusion: state_entry.u.get(offset as usize) != 0,
                face_occlusion: face_indices[offset as usize].map(&mut tuple),
            };
            // Vanilla's default legacySolid uses cached collision bounds;
            // forceSolidOn/Off require additional registry data.
            let blocks_motion = collides
                && !matches!(name, "cobweb" | "bamboo_sapling" | "powder_snow")
                && match shape.as_deref() {
                    Some(boxes) if boxes.is_empty() => false,
                    Some(boxes) => {
                        let min = [0, 1, 2].map(|axis| {
                            boxes.iter().map(|b| b[axis]).fold(f64::INFINITY, f64::min)
                        });
                        let max = [3, 4, 5].map(|axis| {
                            boxes
                                .iter()
                                .map(|b| b[axis])
                                .fold(f64::NEG_INFINITY, f64::max)
                        });
                        let (x, y, z) = (max[0] - min[0], max[1] - min[1], max[2] - min[2]);
                        (x + y + z) / 3.0 >= 0.729_166_666_666_666_6 || y >= 1.0
                    }
                    None => true,
                };
            table.push(BlockData {
                id: name,
                default_state,
                properties,
                behavior,
                shape,
                outline,
                max_horizontal_offset,
                is_air,
                map_color_rgb: state_entry.m.as_ref().map(|v| v.get(offset as usize)),
                falling_dust_rgb: state_entry.q.as_ref().map(|v| v.get(offset as usize)),
                spawn_terrain_particles: state_entry
                    .s
                    .as_ref()
                    .map(|v| v.get(offset as usize) != 0),
                render_shape_invisible: state_entry.r.as_ref().map(|v| v.get(offset as usize) != 0),
                solid_render: state_entry.t.as_ref().map(|v| v.get(offset as usize) != 0),
                is_leaves_block: state_entry
                    .l
                    .as_ref()
                    .is_some_and(|v| v.get(offset as usize) != 0),
                liquid_block_container: state_entry.k.as_ref().map(|v| v.get(offset as usize) != 0),
                can_place_liquid_water: state_entry.n.as_ref().map(|v| v.get(offset as usize) != 0),
                bonemeal_type: state_entry
                    .b
                    .as_ref()
                    .map(|v| v.get(offset as usize))
                    .filter(|&kind| kind != 0),
                bonemeal_particle_offset: state_entry
                    .g
                    .as_ref()
                    .map(|v| v.get(offset as usize))
                    .unwrap_or([0, 0, 0]),
                collision_shape_full_block: state_entry
                    .h
                    .as_ref()
                    .map(|v| v.get(offset as usize) != 0),
                can_be_replaced_by_water: state_entry
                    .w
                    .as_ref()
                    .map(|v| v.get(offset as usize) != 0),
                dynamic_shape: state_entry
                    .i
                    .as_ref()
                    .is_some_and(|v| v.get(offset as usize) != 0),
                shape_max_y_32nds: state_entry.j.as_ref().map(|v| v.get(offset as usize)),
                collides,
                blocks_motion: state_entry
                    .v
                    .as_ref()
                    .map(|v| v.get(offset as usize) != 0)
                    .unwrap_or(blocks_motion),
                replaceable: registry::block_is_replaceable(name),
                fluid,
                light,
            });
        }
    }

    assert_eq!(
        table.len() as u32,
        file.state_count,
        "block-state data table size mismatch for {}",
        file.version
    );
    table
}

fn decode_face_mask(hex: &str) -> FaceMask {
    assert_eq!(hex.len(), 64, "face mask must be 64 hex chars");
    std::array::from_fn(|v| {
        u16::from_str_radix(&hex[v * 4..v * 4 + 4], 16).expect("invalid face-mask hex")
    })
}

/// Expands a light entry's `f` field into per-state mask-dictionary tuples.
fn light_face_indices(entry: &StateEntry, count: usize) -> Vec<Option<[u32; 6]>> {
    let Some(f) = &entry.f else {
        return vec![None; count];
    };
    let arr = f
        .as_array()
        .unwrap_or_else(|| panic!("{}: face-mask field is not an array", entry.name));
    let parse_tuple = |values: &[serde_json::Value]| -> [u32; 6] {
        assert_eq!(values.len(), 6, "{}: face-mask tuple length", entry.name);
        std::array::from_fn(|i| {
            values[i]
                .as_u64()
                .unwrap_or_else(|| panic!("{}: non-numeric face-mask index", entry.name))
                as u32
        })
    };
    if arr.first().is_some_and(serde_json::Value::is_number) {
        // Uniform across the block: a single 6-index tuple.
        return vec![Some(parse_tuple(arr)); count];
    }
    assert_eq!(arr.len(), count, "{}: face-mask entry count", entry.name);
    arr.iter()
        .map(|v| {
            if v.is_null() {
                None
            } else {
                Some(parse_tuple(v.as_array().unwrap_or_else(|| {
                    panic!("{}: face-mask entry is not a tuple", entry.name)
                })))
            }
        })
        .collect()
}

fn state_fluid(name: &'static str, props: &PropMap) -> Fluid {
    match name {
        "water" | "lava" => {
            let level: u8 = props.get("level").and_then(|l| l.parse().ok()).unwrap_or(0);
            let kind = if name == "water" {
                FluidKind::Water
            } else {
                FluidKind::Lava
            };
            if level >= 8 {
                Fluid {
                    kind,
                    amount: 8,
                    falling: true,
                }
            } else {
                Fluid {
                    kind,
                    amount: 8 - level,
                    falling: false,
                }
            }
        }
        "bubble_column" => FULL_WATER,
        _ if IMPLICIT_WATER.contains(&name) => FULL_WATER,
        _ if props.get("waterlogged") == Some("true") => FULL_WATER,
        _ => NO_FLUID,
    }
}

