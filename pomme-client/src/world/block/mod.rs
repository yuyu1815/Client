/// Per-block fields; each is a scalar when uniform across the block's
/// states, else one value per state. `f` is 6 mask-dictionary indices —
/// a single tuple when uniform, else a per-state list of tuple-or-null.
#[derive(serde::Deserialize)]
struct StateEntry {
    name: String,
    e: ScalarOrPerState,
    d: ScalarOrPerState,
    p: ScalarOrPerState,
    o: ScalarOrPerState,
    u: ScalarOrPerState,
    /// `hasCollision`; block-level in vanilla, so always a scalar.
    c: u8,
    #[serde(default)]
    f: Option<serde_json::Value>,
    #[serde(default)]
    m: Option<ScalarOrPerStateU32>,
    #[serde(default)]
    q: Option<ScalarOrPerStateU32>,
    #[serde(default)]
    s: Option<ScalarOrPerState>,
    #[serde(default)]
    r: Option<ScalarOrPerState>,
    #[serde(default)]
    t: Option<ScalarOrPerState>,
    #[serde(default)]
    v: Option<ScalarOrPerState>,
    #[serde(default)]
    l: Option<ScalarOrPerState>,
    /// Exact Java `block instanceof LiquidBlockContainer` type identity.
    #[serde(default)]
    k: Option<ScalarOrPerState>,
    /// Java `LiquidBlockContainer.canPlaceLiquid(null, ..., Fluids.WATER)`.
    #[serde(default)]
    n: Option<ScalarOrPerState>,
    /// Exact Java `BonemealableBlock.Type`: 0 not bonemealable, 1 spreader, 2
    /// grower.
    #[serde(default)]
    b: Option<ScalarOrPerState>,
    /// Exact `getParticlePos(BlockPos.ZERO)` offset, uniform tuple or per-state
    /// tuples.
    #[serde(default)]
    g: Option<ScalarOrPerStateOffset>,
    /// Java `isCollisionShapeFullBlock(EmptyBlockGetter, ZERO)`; exact shape
    /// union.
    #[serde(default)]
    h: Option<ScalarOrPerState>,
    /// Exact Java `BlockState.canBeReplaced(Fluids.WATER)` result.
    #[serde(default)]
    w: Option<ScalarOrPerState>,
    #[serde(default)]
    i: Option<ScalarOrPerState>,
    /// `getShape(EmptyBlockGetter, ZERO).max(Y)` in thirty-seconds; 255 is
    /// empty.
    #[serde(default)]
    j: Option<ScalarOrPerState>,
}

#[derive(serde::Deserialize)]
#[serde(untagged)]
enum ScalarOrPerState {
    One(u8),
    Many(Vec<u8>),
}

#[derive(serde::Deserialize)]
#[serde(untagged)]
enum ScalarOrPerStateOffset {
    One([i32; 3]),
    Many(Vec<[i32; 3]>),
}

impl ScalarOrPerStateOffset {
    fn get(&self, offset: usize) -> [i32; 3] {
        match self {
            Self::One(v) => *v,
            Self::Many(vs) => vs[offset],
        }
    }
}

#[derive(serde::Deserialize)]
#[serde(untagged)]
enum ScalarOrPerStateU32 {
    One(u32),
    Many(Vec<u32>),
}

impl ScalarOrPerStateU32 {
    fn get(&self, offset: usize) -> u32 {
        match self {
            Self::One(v) => *v,
            Self::Many(vs) => vs[offset],
        }
    }
}

impl ScalarOrPerState {
    fn get(&self, offset: usize) -> u8 {
        match self {
            Self::One(v) => *v,
            Self::Many(vs) => vs[offset],
        }
    }
}

/// One version's embedded block tables. `blocks` is the state layout (ids and
/// properties from the data-generator report); `state` (`just stategen`)
/// holds the per-state values vanilla bakes at runtime, dumped by running its
/// own code.
struct EmbeddedBlocks {
    protocol: i32,
    blocks: &'static str,
    state: &'static str,
    shapes: Option<&'static str>,
}

/// The per-version state tables and optional vanilla-verified shape overrides.
macro_rules! embedded_blocks {
    ($protocol:expr, $version:literal) => {
        EmbeddedBlocks {
            protocol: $protocol,
            blocks: include_str!(concat!("data/blocks-", $version, ".json")),
            state: include_str!(concat!("data/state-", $version, ".json")),
            shapes: None,
        }
    };
    ($protocol:expr, $version:literal, $shape_version:literal) => {
        EmbeddedBlocks {
            protocol: $protocol,
            blocks: include_str!(concat!("data/blocks-", $version, ".json")),
            state: include_str!(concat!("data/state-", $version, ".json")),
            shapes: Some(include_str!(concat!(
                "data/shapes-",
                $shape_version,
                ".json"
            ))),
        }
    };
}

